import { Injectable, NotFoundException } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import axios from 'axios';
import { RecoveryPlan, PlanStatus } from '../models/recovery-plan.entity';
import { RecoveryPlanItem } from '../models/recovery-plan-item.entity';
import { AbsenceService } from '../../absence/services/absence.service';
import { AssessmentService } from '../../assessment/services/assessment.service';
import { ContentService } from '../../content/services/content.service';
import { ApprovePlanDto } from '../dto/approve-plan.dto';
import { UpdateProgressDto } from '../dto/update-progress.dto';

@Injectable()
export class RecoveryService {
  private readonly aiServiceUrl = process.env.AI_SERVICE_URL || 'http://localhost:8000';

  constructor(
    @InjectRepository(RecoveryPlan)
    private readonly planRepo: Repository<RecoveryPlan>,
    @InjectRepository(RecoveryPlanItem)
    private readonly itemRepo: Repository<RecoveryPlanItem>,
    private readonly absenceService: AbsenceService,
    private readonly assessmentService: AssessmentService,
    private readonly contentService: ContentService,
  ) {}

  async generateRecoveryPlan(studentId: string): Promise<RecoveryPlan> {
    const gaps = await this.absenceService.getLearningGaps(studentId);
    const assessments = await this.assessmentService.getStudentAssessments(studentId);
    const availableContent = await this.contentService.findAll();

    let planData: any = null;
    try {
      const response = await axios.post(`${this.aiServiceUrl}/api/ai/generate-plan`, {
        student_id: studentId,
        gaps,
        assessments,
        available_content: availableContent,
      });
      planData = response.data?.data;
    } catch {
      // Fallback plan if AI is offline
      planData = {
        title: 'Disruption Catch-Up Pathway',
        summary: 'Focused plan to bridge core concepts missed during recent disruptions.',
        total_estimated_hours: (gaps.length || 1) * 2,
        steps: gaps.map((g: any, idx: number) => ({
          order: idx + 1,
          topic_id: g.topicId,
          topic_name: g.topicName,
          estimated_hours: 2,
          reasoning: `Prerequisite catch-up for ${g.topicName}`,
        })),
      };
    }

    const recoveryPlan = this.planRepo.create({
      studentId,
      status: PlanStatus.PENDING,
      aiGeneratedPlan: planData,
      totalHours: planData?.total_estimated_hours || 0,
      teacherNotes: 'Generated by ShikkhaBridge AI Recovery Engine. Pending teacher verification.',
    });
    const savedPlan = await this.planRepo.save(recoveryPlan);

    const steps = planData?.steps || [];
    const items = steps.map((step: any, index: number) =>
      this.itemRepo.create({
        planId: savedPlan.id,
        topicId: step.topic_id,
        order: step.order || index + 1,
        estimatedHours: step.estimated_hours || 2,
        completed: false,
      }),
    );
    await this.itemRepo.save(items);

    return this.getPlanById(savedPlan.id);
  }

  async getStudentPlans(studentId: string): Promise<RecoveryPlan[]> {
    return this.planRepo.find({
      where: { studentId },
      relations: ['items', 'items.topic', 'items.content', 'teacher'],
      order: { createdAt: 'DESC' },
    });
  }

  async getPlanById(id: string): Promise<RecoveryPlan> {
    const plan = await this.planRepo.findOne({
      where: { id },
      relations: ['items', 'items.topic', 'items.content', 'student', 'teacher'],
    });
    if (!plan) throw new NotFoundException('Recovery plan not found');
    return plan;
  }

  async approvePlan(id: string, teacherId: string, dto: ApprovePlanDto): Promise<RecoveryPlan> {
    const plan = await this.getPlanById(id);
    plan.teacherId = teacherId;
    plan.status = dto.status;
    if (dto.teacherNotes) plan.teacherNotes = dto.teacherNotes;
    return this.planRepo.save(plan);
  }

  async updateItemProgress(dto: UpdateProgressDto): Promise<RecoveryPlanItem> {
    const item = await this.itemRepo.findOne({ where: { id: dto.itemId } });
    if (!item) throw new NotFoundException('Plan item not found');
    item.completed = dto.completed;
    item.completedAt = dto.completed ? new Date() : null;
    return this.itemRepo.save(item);
  }

  async getPendingPlans(): Promise<RecoveryPlan[]> {
    return this.planRepo.find({
      where: { status: PlanStatus.PENDING },
      relations: ['student', 'items', 'items.topic'],
      order: { createdAt: 'DESC' },
    });
  }
}
